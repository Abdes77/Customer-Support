import type { PlaybookOrigin } from "@repo/db";

import { Badge, type BadgeTone } from "@/components/ui/badge";

const ORIGINS: Readonly<
  Record<PlaybookOrigin, { label: string; tone: BadgeTone; explain: string }>
> = {
  generated: {
    label: "Generated by Claude",
    tone: "blue",
    explain: "Researched on the web and written by the Claude API, with its sources listed.",
  },
  starter: {
    label: "Built-in starter, not generated",
    tone: "amber",
    explain:
      "This is the built-in starter playbook. It was NOT researched or written by the Claude API, because this deployment has no API key. Review it, or regenerate it once a key is set.",
  },
  manual: {
    label: "Edited by hand",
    tone: "neutral",
    explain: "Saved by a person in the playbook editor.",
  },
  rollback: {
    label: "Rolled back",
    tone: "neutral",
    explain: "A copy of an earlier version, made active again.",
  },
  import: { label: "Imported", tone: "neutral", explain: "Imported from a file." },
};

export function OriginBadge({ origin }: { readonly origin: PlaybookOrigin }) {
  const { label, tone } = ORIGINS[origin];
  return <Badge tone={tone}>{label}</Badge>;
}

export function originExplanation(origin: PlaybookOrigin): string {
  return ORIGINS[origin].explain;
}
