import { createHash } from "node:crypto";
import path from "node:path";
import { gzipSync } from "node:zlib";

import { build } from "esbuild";

export const PACKAGE_ROOT = path.resolve(import.meta.dirname, "..");
export const ENTRY = path.join(PACKAGE_ROOT, "src/browser/main.ts");
export const GENERATED = path.join(PACKAGE_ROOT, "src/bundle.generated.ts");

/**
 * The size budget of the script a business's website loads, after gzip (what travels). The
 * widget must not slow the host page down: it is loaded `async`, makes one small request on
 * load, and stays well under the size of a typical web font.
 */
export const GZIP_BUDGET_BYTES = 12 * 1024;
export const RAW_BUDGET_BYTES = 36 * 1024;

export interface WidgetBundle {
  readonly code: string;
  readonly sha256: string;
  readonly version: string;
  readonly rawBytes: number;
  readonly gzipBytes: number;
}

/** Bundles `src/browser/main.ts` into one minified IIFE. Deterministic for one esbuild version. */
export async function bundleWidget(): Promise<WidgetBundle> {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    charset: "utf8",
    write: false,
    logLevel: "silent",
  });
  const code = result.outputFiles[0]!.text.trim();
  const sha256 = createHash("sha256").update(code).digest("hex");
  return {
    code,
    sha256,
    version: sha256.slice(0, 12),
    rawBytes: Buffer.byteLength(code),
    gzipBytes: gzipSync(code, { level: 9 }).length,
  };
}

export function generatedModule(bundle: WidgetBundle): string {
  return [
    "// Generated by `pnpm --filter @repo/widget-embed build` from src/browser. Do not edit.",
    `// ${bundle.rawBytes} bytes, ${bundle.gzipBytes} bytes gzipped.`,
    `export const WIDGET_SCRIPT_VERSION = ${JSON.stringify(bundle.version)};`,
    `export const WIDGET_SCRIPT_SHA256 = ${JSON.stringify(bundle.sha256)};`,
    `export const WIDGET_SCRIPT = ${JSON.stringify(bundle.code)};`,
    "",
  ].join("\n");
}
